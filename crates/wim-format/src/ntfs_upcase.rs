/// Collate UTF-16LE names by NTFS uppercase units, then by original units.
/// Inputs represent complete little-endian code units; no Unicode normalization occurs.
pub fn compare_names(a: &[u8], b: &[u8]) -> core::cmp::Ordering {
    fn units(bytes: &[u8]) -> impl Iterator<Item = u16> + '_ {
        bytes
            .chunks_exact(2)
            .map(|u| u16::from_le_bytes([u[0], u[1]]))
    }
    units(a)
        .map(uppercase)
        .cmp(units(b).map(uppercase))
        .then_with(|| units(a).cmp(units(b)))
}
