const fn table() -> [u16; 65536] {
    let mut table = [0u16; 65536];
    let mut position = 0;
    let mut input = 0;
    while position < table.len() {
        let mut length = COMPRESSED[input];
        let mut source = COMPRESSED[input + 1] as usize;
        input += 2;
        if length == 0 {
            table[position] = source as u16;
            position += 1;
        } else {
            while length != 0 {
                table[position] = table[source];
                position += 1;
                source += 1;
                length -= 1;
            }
        }
    }
    let mut i = 0;
    while i < table.len() {
        table[i] = table[i].wrapping_add(i as u16);
        i += 1;
    }
    table
}
static UPCASE: [u16; 65536] = table();
/// Map one UTF-16 code unit using the original default NTFS uppercase table.
pub fn uppercase(unit: u16) -> u16 {
    UPCASE[unit as usize]
}
